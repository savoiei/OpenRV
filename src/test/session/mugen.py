"""Generate the write-phase Mu -init script for a Case.

The script runs the Case's ops in order (once, after all sources are loaded)
and prints one line per op:  ##RVSESSION## <op_index> | actual=<sessionFileName()>
The harness owns expected values and computes verdicts.

Paths: each op's Mu path is the string RV must receive. Relative ops
(Op.relative) pass the relative string verbatim and resolve against the rvio
cwd (the case work dir); absolute ops get the work dir prefixed. Every path is
written through mu_string(), which escapes backslashes and double quotes.

Idioms confirmed by the session spike: the source-load-complete family of
events (source-group-complete, new-source, after-progressive-loading) never
fires under headless `rvio -init`; "render" fires once per output frame with
sources already loaded. commands.unbind() only has a 3-arg (mode, table, event)
form on this build (no tag/key overload), so the one-shot guard uses a
module-global bool checked alongside the redundant-but-harmless unbind call.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
_root = next((p for p in _here.parents if (p / "rvtest" / "__init__.py").is_file()), None)
if _root is None:
    raise SystemExit(f"rvtest package not found above {_here}")
sys.path.insert(0, str(_root))

from rvtest.escape import mu_string  # noqa: E402

from model import Case, Op  # noqa: E402

LOAD_EVENT = "render"
BIND_TAG = "rvt_session"


def _bool(b: bool) -> str:
    return "true" if b else "false"


def op_path(op: Op, work_dir: str) -> str:
    """The path string RV receives for `op`."""
    assert op.path is not None
    return op.path if op.relative else os.path.join(work_dir, op.path)


def _op_call(op: Op, work_dir: str) -> str:
    if op.kind in ("save", "save_as_copy"):
        as_copy = _bool(op.kind == "save_as_copy")
        return (f"commands.saveSession({mu_string(op_path(op, work_dir))}, {as_copy}, "
                f"{_bool(op.compressed)}, {_bool(op.sparse)});")
    if op.kind == "set_filename":
        return f"commands.setSessionFileName({mu_string(op_path(op, work_dir))});"
    if op.kind == "clear":
        return "commands.clearSession();"
    raise ValueError(f"unsupported op kind: {op.kind!r}")


def write_mu_text(case: Case, work_dir: str) -> str:
    n_sources = len(case.sources)
    lines = [
        "// auto-generated by the rv-regression-tests session suite; do not edit",
        "require commands;",
        "",
        "global bool rvt_session_ran = false;",
        "",
        "\\: run_ops (void;)",
        "{",
    ]
    for i, op in enumerate(case.ops):
        lines.append(f"    {_op_call(op, work_dir)}")
        lines.append(
            f'    print("##RVSESSION## {i} | actual=" '
            f'+ commands.sessionFileName() + "\\n");'
        )
    lines += [
        '    print("##RVSESSION## DONE\\n");',
        "}",
        "",
        "\\: on_complete (void; Event ev)",
        "{",
        "    if (ev neq nil) ev.reject();",
        f'    if (!rvt_session_ran && commands.nodesOfType("RVFileSource").size() >= {n_sources})',
        "    {",
        "        rvt_session_ran = true;",
        f'        commands.unbind("default", "global", "{LOAD_EVENT}");',
        "        run_ops();",
        "    }",
        "}",
        "",
        f'commands.bind("default", "global", "{LOAD_EVENT}", on_complete, "{BIND_TAG}");',
        "",
    ]
    return "\n".join(lines)
